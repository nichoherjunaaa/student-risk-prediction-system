def cnn_model(
    input_shape,
    n_classes,
    filters1=32,
    filters2=64,
    dense1=128,
    dense2=64,
    dropout_conv=0.25,
    dropout_dense1=0.5,
    dropout_dense2=0.3,
    kernel_size=(3, 3),
):
    model = keras.Sequential([
        # --- Conv Block 1 ---
        layers.Conv2D(filters1, kernel_size, activation="relu", input_shape=input_shape, padding="same"),
        layers.BatchNormalization(),
        layers.MaxPooling2D((2, 2)),
        layers.Dropout(dropout_conv),

        # --- Conv Block 2 ---
        layers.Conv2D(filters2, kernel_size, activation="relu", padding="same"),
        layers.BatchNormalization(),
        layers.MaxPooling2D((2, 2)),
        layers.Dropout(dropout_conv),

        # --- Dense Block ---
        layers.Flatten(),
        layers.Dense(dense1, activation="relu"),
        layers.BatchNormalization(),
        layers.Dropout(dropout_dense1),

        layers.Dense(dense2, activation="relu"),
        layers.Dropout(dropout_dense2),

        # --- Output ---
        layers.Dense(
            n_classes if n_classes > 2 else 1,
            activation="softmax" if n_classes > 2 else "sigmoid"
        ),
    ])
    return model

