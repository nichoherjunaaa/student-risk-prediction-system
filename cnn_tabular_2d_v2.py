def find_grid_dimensions(n):
    factors = []
    for i in range(1, int(np.sqrt(n)) + 1):
        if n % i == 0:
            factors.append((i, n // i))
    return factors[-1] if factors else (int(np.sqrt(n)), int(np.ceil(n / np.sqrt(n))))

