import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score

def cnn_permutation_importance(model, X_scaled, y, feature_names, height, width, pad_size):

    baseline_input = np.pad(X_scaled, ((0,0),(0,pad_size)), mode="constant")
    baseline_input = baseline_input.reshape(-1, height, width, 1)

    baseline_score = roc_auc_score(y, model.predict(baseline_input).ravel())

    importances = []

    for i in range(X_scaled.shape[1]):

        X_perm = X_scaled.copy()
        np.random.shuffle(X_perm[:, i])

        X_perm_pad = np.pad(X_perm, ((0,0),(0,pad_size)), mode="constant")
        X_perm_reshaped = X_perm_pad.reshape(-1, height, width, 1)

        score = roc_auc_score(y, model.predict(X_perm_reshaped).ravel())

        importances.append(baseline_score - score)

    return pd.Series(importances, index=feature_names)

